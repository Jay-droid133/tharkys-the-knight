#!/usr/bin/env python3
"""
build_screen_gaps.py — Phase 1 of monster AI v2

Uses the EXPORTED ASM files as source of truth (not level_data.json) so that
auto-fill border sprites generated by the level editor at export time are
included in the walkgrid. Otherwise openings would be emitted over auto-fill
blockers.

Sources:
  code/screen_data.asm   — MapTable: screen (X,Y) → exported template_id
  code/screen_rooms.asm  — Room_Txx: placements (id, x, y) per exported template
  code/bg_gfx.asm + bg_gfx_b.asm — sprite dimensions (height_px, width_chars)

Output: code/screen_gaps.asm

Per-opening coord = top-left char of the monster's 2x3 footprint at spawn.
Side-specific fixed axis (N:cy=2, S:cy=17, W:cx=2, E:cx=27).
"""

import re
import sys
from pathlib import Path

# ---- Constants (mirror editor / runtime) ------------------------------------

GRID_W = 32          # chars per screen (X)
GRID_H = 22          # chars per screen (Y)
TILE_SIZE = 8        # px per char
MAP_W = 16           # screens wide
MAP_H = 16           # screens tall

MIN_POCKET_SIZE = 20 # cells min in connected region for a gap to be valid

# Monster footprint (in chars). Monster sprite ≈ 16 × 21 px → 2 × 3 chars.
MONSTER_FOOT_W = 2
MONSTER_FOOT_H = 3

# Per-side spawn anchor: where the monster's top-left lands when entering.
# MAI_ENTRY_OFFSET = 16 px = 2 chars. Char-aligned so footprint check is clean.
# CollisionMap cy = pixel_y/8 - BG_Y_OFFSET (=2).
#   N side: pixel Y = SCREEN_MIN_Y(16) + OFFSET(16) = 32 → cy = 32/8 - 2 = 2
#   S side: pixel Y = SCREEN_MAX_Y(168) - OFFSET(16) = 152 → cy = 152/8 - 2 = 17
#   W side: pixel X = OFFSET(16) = 16 → cx = 2
#   E side: pixel X = SCREEN_MAX_X(232) - OFFSET(16) = 216 → cx = 27
# Coord stored in the gap record = position of the variable axis (cx for N/S,
# cy for W/E) of the monster's top-left.
SIDE_N, SIDE_S, SIDE_W, SIDE_E = 0, 1, 2, 3
SIDE_NAMES = {SIDE_N: 'N', SIDE_S: 'S', SIDE_W: 'W', SIDE_E: 'E'}
SIDE_SPAWN_CY = {SIDE_N: 0,  SIDE_S: 19}  # fixed cy for horizontal borders (anchored AT border)
SIDE_SPAWN_CX = {SIDE_W: 0,  SIDE_E: 29}  # fixed cx for vertical borders

# Per-screen forced gap overrides. Keyed by (rx, ry) (screen coords on map).
# Each entry is a list of (side, coord) tuples to ADD to the auto-detected
# gaps for that screen, bypassing the MIN_POCKET_SIZE / monster_fits_at
# filters. Use solo para rooms donde la auto-deteccion falla: tipicamente
# rooms densas con una sola entrada minuscula cuyo pocket walkable cae
# debajo de MIN_POCKET_SIZE.
#
# Caso actual:
#   (15, 6) Iglesia: south @ 15. La sala es casi toda paredes/fachada,
#   solo la franja sur entre suelo y vano es transitable (~14 celdas <
#   MIN_POCKET_SIZE=20). Sin este override, la sala acaba en
#   ScreenGapsNone -> SpawnMonsters cae al fallback LastEntryPos, que
#   puede aterrizar dentro de la iglesia (ej. valor inicial por defecto
#   120,90 mapea al area del vano de la puerta). Resultado visible:
#   "los monstruos salen de la iglesia" en lugar de entrar por el sur.
FORCED_GAPS = {
    (15, 6): [(SIDE_S, 15)],
}


# ---- ASM parsers ------------------------------------------------------------

def parse_map_table(path):
    """Parse MapTable from screen_data.asm. Return [y][x] = template_id."""
    rows = []
    with open(path, encoding='utf-8') as f:
        in_map = False
        for line in f:
            stripped = line.strip()
            if stripped.startswith('MapTable:'):
                in_map = True
                continue
            if not in_map:
                continue
            if not stripped or stripped.startswith(';'):
                if len(rows) == MAP_H:
                    break
                continue
            m = re.search(r'DEFB\s+([0-9,\s]+)', stripped)
            if not m:
                if rows:
                    break
                continue
            nums = [int(x.strip()) for x in m.group(1).rstrip(',').split(',') if x.strip()]
            rows.append(nums)
            if len(rows) == MAP_H:
                break
    if len(rows) != MAP_H:
        raise RuntimeError(f"MapTable parse: got {len(rows)} rows, expected {MAP_H}")
    return rows


def parse_rooms(path):
    """Parse Room_Txx blocks from screen_rooms.asm.
    Return dict: template_id → list of (sprite_id, x_char, y_char).
    """
    templates = {}
    current_id = None
    current_list = None
    label_re = re.compile(r'^Room_T(\d+)\s*:')
    defb_re = re.compile(r'^\s*DEFB\s+(.*?)(?:;.*)?$')
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            m = label_re.match(line.strip())
            if m:
                if current_id is not None:
                    templates[current_id] = current_list
                current_id = int(m.group(1))
                current_list = []
                continue
            if current_id is None:
                continue
            m = defb_re.match(line)
            if not m:
                continue
            body = m.group(1).strip().rstrip(',')
            # Handle $FF terminator (single field, possibly with comment stripped)
            if re.match(r'^\$FF\s*$', body):
                templates[current_id] = current_list
                current_id = None
                current_list = None
                continue
            # Otherwise DEFB id, x, y [,v] — x may have bit 7 set (tint flag)
            parts = [p.strip() for p in body.split(',')]
            if len(parts) < 3:
                continue
            try:
                sid = int(parts[0])
                x_raw = int(parts[1])
                y = int(parts[2])
            except ValueError:
                continue
            x_char = x_raw & 0x7F
            current_list.append((sid, x_char, y))
    if current_id is not None and current_list is not None:
        templates[current_id] = current_list
    return templates


def parse_bg_dims(paths):
    """Parse BgGfx_*:* labels from bg_gfx.asm and bg_gfx_b.asm. Return dict
    sprite_id → (height_px, width_chars). Follows EQU aliases.
    """
    id_to_label = {}        # "BgGfx_foo" → id (from label-with-comment)
    label_to_dims = {}      # "BgGfx_foo" → (h_px, w_chars)
    label_to_alias = {}     # "BgGfx_foo" → "BgGfx_bar" (alias target)

    label_re = re.compile(r'^(BgGfx_\S+?)\s*:\s*(?:;.*?BG(\d+))?')
    equ_re = re.compile(
        r'^(BgGfx_\S+)\s+EQU\s+(BgGfx_\S+)\s*(?:;.*?BG(\d+))?'
    )
    defb_re = re.compile(r'^\s*DEFB\s+(\d+)\s*,\s*(\d+)')

    for path in paths:
        current_label = None
        awaiting_dims = False
        with open(path, encoding='utf-8') as f:
            for line in f:
                line = line.rstrip('\n')
                s = line.strip()
                m_equ = equ_re.match(s)
                if m_equ:
                    alias, target, sid_str = m_equ.group(1), m_equ.group(2), m_equ.group(3)
                    label_to_alias[alias] = target
                    if sid_str:
                        id_to_label[int(sid_str)] = alias
                    continue
                m_lbl = label_re.match(s)
                if m_lbl:
                    current_label = m_lbl.group(1)
                    sid_str = m_lbl.group(2)
                    if sid_str:
                        id_to_label[int(sid_str)] = current_label
                    awaiting_dims = True
                    continue
                if awaiting_dims:
                    m_d = defb_re.match(line)
                    if m_d:
                        h = int(m_d.group(1))
                        w_raw = int(m_d.group(2))
                        w_chars = w_raw & 0x7F   # strip RLE flag
                        label_to_dims[current_label] = (h, w_chars)
                        awaiting_dims = False

    def resolve(label):
        seen = set()
        while label in label_to_alias and label not in seen:
            seen.add(label)
            label = label_to_alias[label]
        return label_to_dims.get(label)

    dims = {}
    for sid, label in id_to_label.items():
        hw = resolve(label)
        if hw is not None:
            dims[sid] = hw
    return dims


# ---- Per-screen walkability -------------------------------------------------

def screen_walkgrid(rx, ry, map_table, room_templates, bg_dims):
    """Return [y][x] walkgrid (1=free, 0=blocked) or None if no template."""
    tid = map_table[ry][rx]
    if tid == 0:
        return None
    placements = room_templates.get(tid)
    if placements is None:
        return [[1] * GRID_W for _ in range(GRID_H)]
    blocked = set()
    for (sid, px, py) in placements:
        hw = bg_dims.get(sid)
        if hw is None:
            continue
        h_px, w_chars = hw
        if h_px <= 0 or w_chars <= 0:
            continue
        ch = (h_px + TILE_SIZE - 1) // TILE_SIZE
        cw = w_chars
        for dy in range(ch):
            for dx in range(cw):
                cx = px + dx
                cy = py + dy
                if 0 <= cx < GRID_W and 0 <= cy < GRID_H:
                    blocked.add((cx, cy))
    return [[0 if (x, y) in blocked else 1
             for x in range(GRID_W)]
            for y in range(GRID_H)]


# ---- Connected components & gap filtering -----------------------------------

def connected_components(grid):
    """Return list of components, each a set of (x,y)."""
    seen = [[False] * GRID_W for _ in range(GRID_H)]
    comps = []
    for sy in range(GRID_H):
        for sx in range(GRID_W):
            if not grid[sy][sx] or seen[sy][sx]:
                continue
            stack = [(sx, sy)]
            comp = set()
            while stack:
                x, y = stack.pop()
                if not (0 <= x < GRID_W and 0 <= y < GRID_H):
                    continue
                if seen[y][x] or not grid[y][x]:
                    continue
                seen[y][x] = True
                comp.add((x, y))
                stack.extend([(x+1, y), (x-1, y), (x, y+1), (x, y-1)])
            comps.append(comp)
    return comps


def monster_fits_at(grid, side, coord):
    """Check if the 2x3 monster footprint fits entirely in walkable cells at
    the spawn position associated with this opening candidate.

    coord = variable axis: cx for N/S borders, cy for W/E borders.
    """
    if side in (SIDE_N, SIDE_S):
        cy_top = SIDE_SPAWN_CY[side]
        cx_left = coord
    else:
        cx_left = SIDE_SPAWN_CX[side]
        cy_top = coord

    for dy in range(MONSTER_FOOT_H):
        for dx in range(MONSTER_FOOT_W):
            cx = cx_left + dx
            cy = cy_top + dy
            if not (0 <= cx < GRID_W and 0 <= cy < GRID_H):
                return False
            if not grid[cy][cx]:
                return False
    return True


def spawn_in_main_region(comp_of, comps, side, coord):
    """True iff the spawn footprint lands in any walkable region with
    >= MIN_POCKET_SIZE cells. Multi-component rooms (e.g. dual W with a
    horizontal wall splitting upper/lower) need gaps for BOTH components,
    not just the largest. MIN_POCKET_SIZE still filters tiny dead pockets."""
    if not comps:
        return False
    if side in (SIDE_N, SIDE_S):
        cy, cx = SIDE_SPAWN_CY[side], coord
    else:
        cx, cy = SIDE_SPAWN_CX[side], coord
    comp_idx = comp_of.get((cx, cy))
    if comp_idx is None:
        return False
    return len(comps[comp_idx]) >= MIN_POCKET_SIZE


def filter_gaps(grid, comps):
    """Return (valid_openings, discarded).

    valid_openings: list of (side, midpoint_coord). coord = cx (N/S) or cy (W/E)
                    of the monster's top-left anchor. Runs of contiguous valid
                    coords are coalesced; midpoint of the run is emitted.
    discarded: list of (side, coord, reason) for the report (debug only).
    """
    if not comps:
        return [], []
    comp_of = {}
    for i, comp in enumerate(comps):
        for cell in comp:
            comp_of[cell] = i

    valid_openings = []
    discarded = []

    # Variable axis: cx ranges 0..29 (to allow cx+1), cy ranges 0..19 (cy+2)
    def side_range(side):
        if side in (SIDE_N, SIDE_S):
            return range(GRID_W - MONSTER_FOOT_W + 1)
        return range(GRID_H - MONSTER_FOOT_H + 1)

    for side in (SIDE_N, SIDE_S, SIDE_W, SIDE_E):
        run_start = None
        for coord in side_range(side):
            ok = monster_fits_at(grid, side, coord) and \
                 spawn_in_main_region(comp_of, comps, side, coord)
            if ok:
                if run_start is None:
                    run_start = coord
            else:
                if run_start is not None:
                    mid = (run_start + coord - 1) // 2
                    valid_openings.append((side, mid))
                    run_start = None
        if run_start is not None:
            end = list(side_range(side))[-1]
            mid = (run_start + end) // 2
            valid_openings.append((side, mid))

    return valid_openings, discarded


# ---- ASM emission -----------------------------------------------------------

def screen_label(rx, ry):
    return f"ScreenGaps_{ry:X}{rx:X}"


def emit_asm(all_data, report, out_path):
    """Write the generated ASM."""
    lines = []
    lines.append("; ==============================================================================")
    lines.append("; SCREEN GAPS (bank 6)")
    lines.append("; Auto-generated by tools/build_screen_gaps.py — DO NOT EDIT BY HAND.")
    lines.append(";")
    lines.append("; Each opening = a contiguous run of walkable border cells that reach")
    lines.append("; the main walkable region (MIN_POCKET_SIZE filter). Coord = midpoint.")
    lines.append(";")
    lines.append(";   ScreenGapsTable   — 256 DEFW ptrs (screen_id = Y*16+X)")
    lines.append(";   ScreenGaps_YX     — DEFB count; then {side, coord} × count")
    lines.append(";     side: 0=N, 1=S, 2=W, 3=E")
    lines.append(";     coord: char col (0-31) N/S; char row (0-21) W/E")
    lines.append(";   ScreenGapsNone    — shared zero record (DEFB 0)")
    lines.append("; ==============================================================================")
    lines.append("")

    lines.append("ScreenGapsTable:")
    for ry in range(MAP_H):
        refs = []
        for rx in range(MAP_W):
            if (rx, ry) in all_data and all_data[(rx, ry)]['gaps']:
                refs.append(screen_label(rx, ry))
            else:
                refs.append("ScreenGapsNone")
        lines.append("    DEFW " + ", ".join(refs) + f"    ; Y={ry}")
    lines.append("")

    lines.append("ScreenGapsNone:")
    lines.append("    DEFB 0")
    lines.append("")

    for (rx, ry), data in sorted(all_data.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        gaps = data['gaps']
        if not gaps:
            continue
        lines.append(f"{screen_label(rx, ry)}:    ; room ({rx},{ry})")
        lines.append(f"    DEFB {len(gaps)}")
        for side, coord in gaps:
            lines.append(f"    DEFB {side}, {coord}    ; {SIDE_NAMES[side]} @ {coord}")
        lines.append("")

    lines.append("ScreenGapsEnd:")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding='utf-8', newline='\n')

    with open(out_path.with_suffix('.report.txt'), 'w', encoding='utf-8') as f:
        f.write(report)


# ---- Main -------------------------------------------------------------------

def main():
    root = Path(__file__).resolve().parent.parent
    code = root / 'code'

    map_table = parse_map_table(code / 'screen_data.asm')
    room_templates = parse_rooms(code / 'screen_rooms.asm')
    bg_dims = parse_bg_dims([code / 'bg_gfx.asm', code / 'bg_gfx_b.asm', code / 'bg_gfx_c.asm'])

    all_data = {}
    report_lines = []
    total_rooms = 0
    total_openings = 0
    total_discarded = 0
    rooms_with_zero_openings = []

    for ry in range(MAP_H):
        for rx in range(MAP_W):
            grid = screen_walkgrid(rx, ry, map_table, room_templates, bg_dims)
            if grid is None:
                continue
            total_rooms += 1
            comps = connected_components(grid)
            valid, discarded = filter_gaps(grid, comps)
            # Aplicar forced overrides (rooms con auto-deteccion fallida).
            forced = FORCED_GAPS.get((rx, ry), [])
            for entry in forced:
                if entry not in valid:
                    valid.append(entry)
            all_data[(rx, ry)] = {
                'gaps': valid,
                'comps': len(comps),
            }
            total_openings += len(valid)
            total_discarded += len(discarded)
            if not valid:
                rooms_with_zero_openings.append((rx, ry))

            report_lines.append(
                f"Room ({rx:2d},{ry:2d})  openings={len(valid):2d}  "
                f"cul-de-sacs={len(discarded):2d}  comps={len(comps)}"
            )
            for side, coord, reason in discarded:
                report_lines.append(
                    f"    DROP {SIDE_NAMES[side]}@{coord}: {reason}"
                )

    gap_bytes = sum(1 + 2 * len(d['gaps']) for d in all_data.values() if d['gaps'])
    ptr_bytes = 256 * 2
    none_bytes = 1
    total_bytes = gap_bytes + ptr_bytes + none_bytes

    summary = [
        "=" * 70,
        f"SUMMARY",
        "=" * 70,
        f"Rooms used         : {total_rooms} / {MAP_W * MAP_H}",
        f"Valid openings     : {total_openings}",
        f"Cul-de-sacs dropped: {total_discarded}",
        f"Rooms with 0 gaps  : {len(rooms_with_zero_openings)}",
    ]
    for rx, ry in rooms_with_zero_openings:
        summary.append(f"    !! ({rx},{ry}) has NO valid gaps — runtime fallback to LastEntryPos")
    summary.extend([
        "",
        f"Bank 6 estimated usage:",
        f"  Pointer table (256×2B) : {ptr_bytes} B",
        f"  Gap records            : {gap_bytes} B",
        f"  None placeholder       : {none_bytes} B",
        f"  TOTAL                  : {total_bytes} B "
        f"({total_bytes / 16384 * 100:.1f}% of bank 6)",
        "=" * 70,
    ])
    report = "\n".join(report_lines + [""] + summary) + "\n"
    print("\n".join(summary))

    out_path = root / 'code' / 'screen_gaps.asm'
    emit_asm(all_data, report, out_path)
    print(f"\nWrote {out_path}")
    print(f"Wrote {out_path.with_suffix('.report.txt')}")


if __name__ == '__main__':
    main()
