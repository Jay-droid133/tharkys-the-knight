#!/usr/bin/env python3
"""Extract pixel data for HUD elements used by tools/hud_viewer.html.

Sources:
  * code/hud_clock_sprites.inc  -- BgGfx_hud_clock + decayed (CPL'd bytes)
  * code/bg_sprites.json        -- lives icon, key variants, compass arrow

Output: tools/hud_elements_existing.json with raw (non-CPL'd) pixel + attr
bytes per element so the visualizer can paint each char from paper/ink + bits.

Re-run this script whenever the source sprites change.
"""

import json
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
INC_PATH   = os.path.join(SCRIPT_DIR, '..', 'code', 'hud_clock_sprites.inc')
JSON_PATH  = os.path.join(SCRIPT_DIR, '..', 'code', 'bg_sprites.json')
OUT_PATH   = os.path.join(SCRIPT_DIR, 'hud_elements_existing.json')
OUT_JS     = os.path.join(SCRIPT_DIR, 'hud_elements_existing.js')

DEFB_RE = re.compile(r'\$([0-9A-Fa-f]{2})')


def parse_inc_block(text, label):
    """Parse a labeled DEFB block from hud_clock_sprites.inc.

    Returns dict with keys: w_px, h_px, pixelBytes (CPL'd here, un-CPL'd below),
    attrBytes.
    """
    # Find label start
    m = re.search(rf'^{re.escape(label)}:.*?\n', text, re.MULTILINE)
    if not m:
        raise RuntimeError(f'Label {label} not found in {INC_PATH}')
    body = text[m.end():]
    # Next blank line or labelled section terminates
    end = re.search(r'\n\s*\n|\n[A-Za-z_][A-Za-z0-9_]*:', body)
    block = body[:end.start()] if end else body

    lines = [ln.strip() for ln in block.splitlines() if ln.strip()]

    # Line 1: DEFB h_px, w_bytes
    sizes = [int(x) for x in re.findall(r'\b(\d+)\b', lines[0])]
    h_px, w_bytes = sizes[0], sizes[1]
    w_px = w_bytes * 8

    expected_pixel = h_px * w_bytes
    expected_attr_h = h_px // 8
    expected_attr_w = w_bytes

    pixel_bytes = []
    attr_bytes = []
    saw_tint = False

    for ln in lines[1:]:
        hexes = DEFB_RE.findall(ln)
        if not hexes:
            # Decimal-only lines (e.g. "DEFB 2, 6  ; attr_h, attr_w") are headers
            continue
        bytes_in_line = [int(h, 16) for h in hexes]

        if not saw_tint:
            if len(bytes_in_line) == 1 and len(pixel_bytes) >= expected_pixel:
                saw_tint = True
                continue
            pixel_bytes.extend(bytes_in_line)
            continue

        # After tint: every hex line is attr data
        attr_bytes.extend(bytes_in_line)

    # Truncate if extra bytes slipped (defensive)
    pixel_bytes = pixel_bytes[:expected_pixel]
    attr_bytes  = attr_bytes[:expected_attr_h * expected_attr_w]

    # hud_clock_sprites.inc stores pixels CPL'd. Un-CPL for natural form.
    pixel_bytes = [b ^ 0xFF for b in pixel_bytes]

    return {
        'w_px':       w_px,
        'h_px':       h_px,
        'w_chars':    w_bytes,
        'h_chars':    h_px // 8,
        'pixelBytes': pixel_bytes,
        'attrBytes':  attr_bytes,
    }


def find_sprite_by_id(sprites, sid):
    for sp in sprites:
        if sp['id'] == sid:
            return sp
    raise RuntimeError(f'sprite id {sid} not in bg_sprites.json')


def from_bg_sprite(sp):
    return {
        'w_px':       sp['w'],
        'h_px':       sp['h'],
        'w_chars':    sp['w'] // 8,
        'h_chars':    sp['h'] // 8,
        'pixelBytes': list(sp['pixelBytes']),
        'attrBytes':  list(sp.get('attrBytes', [])),
    }


def main():
    inc_text = open(INC_PATH, 'r', encoding='utf-8').read()
    json_data = json.load(open(JSON_PATH, 'r', encoding='utf-8'))
    sprites = json_data['sprites']

    out = {}

    # Reloj y su decoracion (bloque fijo) - desde hud_clock_sprites.inc
    out['reloj'] = parse_inc_block(inc_text, 'BgGfx_hud_clock')
    out['reloj_decayed'] = parse_inc_block(inc_text, 'BgGfx_hud_clock_decay')

    # Sprites HUD que viven en bg_sprites.json
    out['vidas_unit'] = from_bg_sprite(find_sprite_by_id(sprites, 253))   # 'lives' 8x8
    out['llave']      = from_bg_sprite(find_sprite_by_id(sprites, 62))    # 'ForestKey' 24x16
    out['brujula']    = from_bg_sprite(find_sprite_by_id(sprites, 36))    # 'magic compass HUD' 16x16

    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=2)

    # JS twin for <script src> loading (works under file:// + preview sandboxes)
    with open(OUT_JS, 'w', encoding='utf-8') as f:
        f.write('// Auto-generated by tools/extract_hud_pixels.py\n')
        f.write('window.HUD_ELEMENTS = ')
        json.dump(out, f)
        f.write(';\n')

    print(f'Wrote {OUT_PATH}')
    print(f'Wrote {OUT_JS}')
    for k, v in out.items():
        print(f'  {k}: {v["w_px"]}x{v["h_px"]}px '
              f'({v["w_chars"]}x{v["h_chars"]} chars), '
              f'{len(v["pixelBytes"])} px bytes, '
              f'{len(v["attrBytes"])} attr bytes')


if __name__ == '__main__':
    sys.exit(main())
