#!/usr/bin/env python3
"""
import_magic_compass_hud.py - Sincroniza sprite ID 36 ("magic compass HUD")
desde bg_sprites.json hacia code/sprite_magic_compass_hud.inc.

El HUD de la brújula mágica usa el sprite ID 36 directamente desde el editor,
pero el formato del compass HUD (Sprite_Compass_*) requiere pixels RAW (no
CPL'd), mientras bg_sprites.json los almacena CPL'd para los BgGfx_*. Este
script hace el puente: extrae los 32 bytes pixel del id 36, aplica XOR $FF
para des-CPL'r, y emite el .inc con `Sprite_Compass_Magic:` + DEFB raw.

Idempotente: si el .inc ya está sincronizado, no escribe nada.

Uso: python tools/import_magic_compass_hud.py
Lanzado desde el .bat de build junto a los otros scripts inject_*/build_*.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BG_JSON = ROOT / 'code' / 'bg_sprites.json'
OUT_INC = ROOT / 'code' / 'sprite_magic_compass_hud.inc'

SPRITE_ID = 36
LABEL = 'Sprite_Compass_Magic'


def find_sprite(data, sid):
    """Locate sprite by id across multiple JSON shapes."""
    if isinstance(data, list):
        for s in data:
            if s.get('id') == sid:
                return s
    sprites = data.get('sprites') or data.get('bgSprites')
    if isinstance(sprites, list):
        for s in sprites:
            if s.get('id') == sid:
                return s
    elif isinstance(sprites, dict):
        return sprites.get(sid) or sprites.get(str(sid))
    # Direct top-level dict?
    for v in data.values():
        if isinstance(v, dict) and v.get('id') == sid:
            return v
    return None


def emit_inc(sp):
    """Emit ASM .inc con Sprite_Compass_Magic + MagicCompassBaseAttrs."""
    px = sp['pixelBytes']
    if len(px) != 32:
        sys.exit(f"ERROR: sprite id {SPRITE_ID} has {len(px)} pixel bytes; expected 32 (16x16 px).")
    attrs = sp.get('attrBytes') or []
    if len(attrs) != 4:
        sys.exit(f"ERROR: sprite id {SPRITE_ID} has {len(attrs)} attr bytes; expected 4 (2x2 chars).")
    # IMPORTANTE: bg_sprites.json almacena pixelBytes RAW (sin CPL'r). Es
    # inject_pickup_sprites.py el que aplica XOR $FF al emitir BgGfx_* en
    # bg_gfx.asm (porque DrawBgGfxSprite espera CPL'd). El compass HUD usa
    # DrawCompassSprite que espera RAW directo igual que Sprite_Compass_N
    # etc., así que NO aplicamos XOR aquí.
    raw = list(px)
    # Attrs base: bit 6 (BRIGHT) clearado. El runtime decide bright per-char:
    # 3 chars con base + char activo con base | $40 (con blink en warning).
    # Esto deja al editor controlar paper+ink+flash y al código el bright.
    base_attrs = [a & 0xBF for a in attrs]
    lines = []
    lines.append(f'; Auto-generated by tools/import_magic_compass_hud.py — DO NOT EDIT BY HAND.')
    lines.append(f'; Sprite ID {SPRITE_ID} ("magic compass HUD") extraído de bg_sprites.json.')
    lines.append('')
    lines.append(f'; Pixels: 32 bytes raw (formato Sprite_Compass_* — sin CPL\'r).')
    lines.append(f'{LABEL}:')
    for i in range(0, 32, 8):
        chunk = raw[i:i+8]
        pairs = [f'${chunk[j]:02X},${chunk[j+1]:02X}' for j in range(0, 8, 2)]
        lines.append('    DEFB ' + ', '.join(pairs))
    lines.append('')
    lines.append(f'; Attrs base (bit 6 BRIGHT clearado: el runtime lo controla por char).')
    lines.append(f'; Editor define paper+ink+flash; el código añade BRIGHT al char activo')
    lines.append(f'; (con blink durante los últimos 5 s).')
    lines.append(f'MagicCompassBaseAttrs:')
    lines.append(f"    DEFB " + ', '.join(f'${a:02X}' for a in base_attrs)
                 + f"    ; (1,1) (2,1) (1,2) (2,2)")
    lines.append('')
    return '\n'.join(lines)


def main():
    raw_json = json.loads(BG_JSON.read_text(encoding='utf-8'))
    sp = find_sprite(raw_json, SPRITE_ID)
    if sp is None:
        sys.exit(f"ERROR: sprite id {SPRITE_ID} not found in {BG_JSON}.")
    new_content = emit_inc(sp)
    if OUT_INC.exists() and OUT_INC.read_text(encoding='utf-8') == new_content:
        print(f"{OUT_INC.name} already in sync. No changes.")
        return 0
    OUT_INC.write_text(new_content, encoding='utf-8', newline='\n')
    print(f"Wrote {OUT_INC} ({len(new_content)} chars).")
    return 0


if __name__ == '__main__':
    sys.exit(main())
