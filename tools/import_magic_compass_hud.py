#!/usr/bin/env python3
"""
import_magic_compass_hud.py - Sincroniza los sprites del HUD compass mágico
desde bg_sprites.json hacia code/sprite_magic_compass_hud.inc.

Dos variantes del HUD compass mágico comparten el mismo render (DrawCompass
override en milestones.asm + PaintMagicCompassAttrs en magic_compass.asm) y
se distinguen en runtime por MagicCompassPermanent:

  - ID 36 ("magic compass HUD")    → Sprite_Compass_Magic        + MagicCompassBaseAttrs
                                    Brújula mágica TEMPORAL (random pickup, con timer).
  - ID 37 ("compass lasting")      → Sprite_Compass_MagicLasting + MagicCompassLastingBaseAttrs
                                    Brújula mágica PERMANENTE (post-cinemática iglesia).

El formato del compass HUD (Sprite_Compass_*) requiere pixels RAW (no CPL'd),
mientras bg_sprites.json los almacena CPL'd para los BgGfx_*. Sin embargo
DrawCompassSprite espera RAW directo igual que Sprite_Compass_N etc., así que
NO aplicamos XOR aquí: los pixelBytes del JSON ya vienen en el formato correcto.

Idempotente: si el .inc ya está sincronizado, no escribe nada.

Uso: python tools/import_magic_compass_hud.py
Lanzado desde el .bat de build junto a los otros scripts inject_*/build_*.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BG_JSON = ROOT / 'code' / 'bg_sprites.json'
OUT_INC = ROOT / 'code' / 'sprite_magic_compass_hud.inc'

# (sprite_id, pixel_label, attrs_label, force_bright, descripcion_corta)
#   force_bright = True  → OR $40 sobre cada attr (BRIGHT siempre on en el HUD).
#   force_bright = False → AND $BF (clearado). El runtime decide el bright por char.
#                          La temporal lo mantiene así por compatibilidad con la lógica
#                          de blink del char activo (aunque hoy el blink vive en
#                          DrawCompassGapHint sobre el gap real, no en el HUD 2×2).
VARIANTS = [
    (36, 'Sprite_Compass_Magic',        'MagicCompassBaseAttrs',        False, 'magic compass HUD (temporal random pickup)'),
    (37, 'Sprite_Compass_MagicLasting', 'MagicCompassLastingBaseAttrs', True,  'compass lasting (permanente post-iglesia, bright forzado)'),
]


def find_sprite(data, sid):
    """Locate sprite by id across multiple JSON shapes."""
    if isinstance(data, list):
        for s in data:
            if s.get('id') == sid:
                return s
    sprites = data.get('sprites') or data.get('bgSprites')
    if isinstance(sprites, list):
        for s in sprites:
            if s.get('id') == sid:
                return s
    elif isinstance(sprites, dict):
        return sprites.get(sid) or sprites.get(str(sid))
    # Direct top-level dict?
    for v in data.values():
        if isinstance(v, dict) and v.get('id') == sid:
            return v
    return None


def emit_variant(sp, sprite_id, pixel_label, attrs_label, force_bright, desc):
    """Emit ASM block para un sprite del HUD compass."""
    px = sp['pixelBytes']
    if len(px) != 32:
        sys.exit(f"ERROR: sprite id {sprite_id} has {len(px)} pixel bytes; expected 32 (16x16 px).")
    attrs = sp.get('attrBytes') or []
    if len(attrs) != 4:
        sys.exit(f"ERROR: sprite id {sprite_id} has {len(attrs)} attr bytes; expected 4 (2x2 chars).")
    raw = list(px)
    if force_bright:
        # BRIGHT forzado on: ignora lo que diga el editor. El editor controla
        # paper+ink+flash (bits 0..5,7); aquí garantizamos bit 6 = 1.
        base_attrs = [a | 0x40 for a in attrs]
        attrs_comment = '; Attrs base (bit 6 BRIGHT forzado on para esta variante).'
    else:
        # BRIGHT off en la tabla: el runtime decide bright per-char (3 chars con
        # base + char activo con base | $40 si hay blink). El editor controla
        # paper+ink+flash; el código añade BRIGHT donde lo necesite.
        base_attrs = [a & 0xBF for a in attrs]
        attrs_comment = '; Attrs base (bit 6 BRIGHT clearado: el runtime lo controla por char).'
    lines = []
    lines.append(f'; --- Sprite ID {sprite_id}: {desc} ---')
    lines.append(f'; Pixels: 32 bytes raw (formato Sprite_Compass_* — sin CPL\'r).')
    lines.append(f'{pixel_label}:')
    for i in range(0, 32, 8):
        chunk = raw[i:i+8]
        pairs = [f'${chunk[j]:02X},${chunk[j+1]:02X}' for j in range(0, 8, 2)]
        lines.append('    DEFB ' + ', '.join(pairs))
    lines.append('')
    lines.append(attrs_comment)
    lines.append(f'{attrs_label}:')
    lines.append(f"    DEFB " + ', '.join(f'${a:02X}' for a in base_attrs)
                 + f"    ; (1,1) (2,1) (1,2) (2,2)")
    lines.append('')
    return lines


def emit_inc(sprites_by_id):
    """Emit el .inc completo con todas las variantes."""
    out = []
    out.append('; Auto-generated by tools/import_magic_compass_hud.py — DO NOT EDIT BY HAND.')
    out.append('; Sprites del HUD compass mágico extraídos de bg_sprites.json.')
    out.append('; Editor define paper+ink+flash; el código añade BRIGHT al char activo')
    out.append('; (con blink durante los últimos 5 s para la variante temporal).')
    out.append('')
    for sprite_id, pixel_label, attrs_label, force_bright, desc in VARIANTS:
        out.extend(emit_variant(sprites_by_id[sprite_id], sprite_id, pixel_label, attrs_label, force_bright, desc))
    return '\n'.join(out)


def main():
    raw_json = json.loads(BG_JSON.read_text(encoding='utf-8'))
    sprites_by_id = {}
    for sprite_id, *_ in VARIANTS:
        sp = find_sprite(raw_json, sprite_id)
        if sp is None:
            sys.exit(f"ERROR: sprite id {sprite_id} not found in {BG_JSON}.")
        sprites_by_id[sprite_id] = sp
    new_content = emit_inc(sprites_by_id)
    if OUT_INC.exists() and OUT_INC.read_text(encoding='utf-8') == new_content:
        print(f"{OUT_INC.name} already in sync. No changes.")
        return 0
    OUT_INC.write_text(new_content, encoding='utf-8', newline='\n')
    print(f"Wrote {OUT_INC} ({len(new_content)} chars).")
    return 0


if __name__ == '__main__':
    sys.exit(main())
