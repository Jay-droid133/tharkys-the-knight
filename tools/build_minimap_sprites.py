#!/usr/bin/env python3
"""
build_minimap_sprites.py — Genera code/minimap_sprites.asm.

Lee code/minimap_types.json (campo room_sprites: {(rx,ry) -> {bytes}})
y emite dos tablas:

  MinimapSpriteData:
      N entradas de 8 bytes c/u (sprites unicos deduplicados).
      Ordenados por frecuencia descendente (sprite 0 = el mas comun).

  MinimapSpriteIndex:
      256 bytes; offset (ry*16 + rx) = indice del sprite que pinta esa sala.
      Rooms sin entrada en room_sprites o cuyo MapTable[ry][rx]==0 reciben 0.

Total RAM:
  N * 8 + 256 B.  Con dedup tipica de este nivel: ~ 22*8 + 256 = 432 B.

Uso (ejecutar tras editar sprites en minimap_sprite_editor.html y Save JSON):

  python tools/build_minimap_sprites.py
"""

import json
import sys
from pathlib import Path
from collections import defaultdict

MAP_W = 16
MAP_H = 16


def main():
    root = Path(__file__).resolve().parent.parent
    code = root / 'code'
    types_path = code / 'minimap_types.json'
    out_path = code / 'minimap_sprites.asm'

    with types_path.open(encoding='utf-8') as f:
        data = json.load(f)

    room_sprites = data.get('room_sprites', {})
    if not room_sprites:
        print('ERROR: no room_sprites en minimap_types.json', file=sys.stderr)
        sys.exit(1)

    # Agrupar por bytes para dedup. Ordenar por frecuencia desc -> ID 0 = mas comun.
    groups = defaultdict(list)
    for key, info in room_sprites.items():
        rx, ry = map(int, key.split(','))
        groups[tuple(info['bytes'])].append((rx, ry))
    sorted_groups = sorted(groups.items(), key=lambda kv: -len(kv[1]))
    sprite_to_idx = {bts: i for i, (bts, _) in enumerate(sorted_groups)}

    # Construir indice 256 B: room (rx, ry) -> sprite idx, 0 si no existe.
    index = [[0] * MAP_W for _ in range(MAP_H)]
    for bts, rooms in sorted_groups:
        idx = sprite_to_idx[bts]
        for rx, ry in rooms:
            index[ry][rx] = idx

    # Emit ASM.
    lines = []
    lines.append('; ==============================================================================')
    lines.append('; MINIMAP SPRITES — Auto-generated by tools/build_minimap_sprites.py — DO NOT EDIT.')
    lines.append(';')
    lines.append(f';  Sprites unicos: {len(sorted_groups)}')
    lines.append(f';  RAM total:      {len(sorted_groups) * 8 + 256} B  '
                 f'({len(sorted_groups) * 8} B data + 256 B index)')
    lines.append(';')
    lines.append('; Formato:')
    lines.append(';   MinimapSpriteData:  N * 8 bytes (sprite 0 primero = el mas comun).')
    lines.append(';   MinimapSpriteIndex: 256 bytes, offset ry*16+rx = sprite idx.')
    lines.append('; ==============================================================================')
    lines.append('')

    # --- MinimapSpriteData ---
    lines.append('MinimapSpriteData:')
    for idx, (bts, rooms) in enumerate(sorted_groups):
        bts_str = ', '.join('$' + format(b, '02X') for b in bts)
        rep_room = sorted(rooms)[0]
        lines.append(f'    DEFB {bts_str}    ; sprite {idx:2d} ({len(rooms):3d} salas, '
                     f'rep ({rep_room[0]},{rep_room[1]}))')
    lines.append('')

    # --- MinimapSpriteIndex ---
    lines.append('MinimapSpriteIndex:')
    for ry in range(MAP_H):
        row = index[ry]
        # 16 valores por fila.
        vals = ', '.join(f'{v:3d}' for v in row)
        lines.append(f'    DEFB {vals}    ; Y={ry}')
    lines.append('')

    out_path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'Wrote {out_path}')
    print(f'  {len(sorted_groups)} sprites unicos x 8 B = {len(sorted_groups) * 8} B data')
    print(f'  256 B index')
    print(f'  TOTAL: {len(sorted_groups) * 8 + 256} B')


if __name__ == '__main__':
    main()
